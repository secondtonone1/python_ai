'''
演示装饰器用法
'''

'''
装饰器实现步骤:
1. 函数嵌套
2. 内层函数引用外层函数的参数，这里引用外层函数的形参，也就是原函数
3. 在外层函数内返回内层函数
4. 在内层函数中装饰原函数
'''


# 原函数
def play_game():
    print('打一局蛋仔派对...')

# 定义装饰器(外层函数接受原函数)
def check(fn):
    # 封装一个内层函数，该内层函数使用外层函数的参数
    # 装饰器就是内层函数使用外层函数的形参(fn函数,原函数)
    def inner():
        # 新增装饰功能
        print('登录验证')
        # 执行原函数的功能
        fn()
    return inner

# 等号左侧的play_game相当于inner函数
play_game = check(play_game)
play_game()